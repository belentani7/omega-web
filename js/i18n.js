export function getLanguage(preference, navigatorLanguage = 'pt') {
  if (VALID_LANGUAGES.includes(preference)) return preference;
  const code = String(navigatorLanguage).toLowerCase().split('-')[0];
  return VALID_LANGUAGES.includes(code) ? code : 'pt';
}

export function translate(language, key, variables = {}) {
  const code = getLanguage(language);
  let text = TRANSLATIONS[code]?.[key] ?? TRANSLATIONS.pt[key] ?? key;
  for (const [name, value] of Object.entries(variables)) {
    text = text.replaceAll('{' + name + '}', String(value));
  }
  return text;
}

export function allTranslations(language) {
  return { ...TRANSLATIONS[getLanguage(language)] };
}

export function validateTranslations() {
  const primaryKeys = Object.keys(TRANSLATIONS.pt);
  const missing = [];
  for (const [language, dictionary] of Object.entries(TRANSLATIONS)) {
    for (const key of primaryKeys) {
      if (typeof dictionary[key] !== 'string') missing.push(language + '.' + key);
    }
  }
  return missing;
}
